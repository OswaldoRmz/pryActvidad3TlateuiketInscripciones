    private void btnRegistrarInscripcionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarInscripcionActionPerformed
        // TODO add your handling code here:
        try {
        // Confirma también el número escrito con el teclado.
        spnMensualidad.commitEdit();

        String nombre = txtNombre1.getText();
        String telefono = txtNumero.getText();
        String disciplina =
                (String) cmbDisciplina.getSelectedItem();

        int mensualidad =
                (Integer) spnMensualidad.getValue();

        inscripcion = new clsInscripcion(
                nombre, telefono, disciplina, mensualidad
        );

        bloquearDatos();
        mostrarResultados();

        JOptionPane.showMessageDialog(
                this, "Inscripción registrada correctamente.");

    } catch (java.text.ParseException ex) {
        mostrarError("Escribe una mensualidad válida en pesos enteros.");

    } catch (IllegalArgumentException ex) {
        mostrarError(ex.getMessage());
    }
    }//GEN-LAST:event_btnRegistrarInscripcionActionPerformed

    private void btnRegistrarPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarPagoActionPerformed
        // TODO add your handling code here:
        if (inscripcion == null) {
        mostrarError("Primero registra la inscripción.");
        return;
    }

    try {       
        spnImporte.commitEdit();

        int monto = (Integer) spnImporte.getValue();

        inscripcion.registrarPago(monto);
        mostrarResultados();

        JOptionPane.showMessageDialog(
                this, "Pago registrado correctamente.");

    } catch (java.text.ParseException ex) {
        mostrarError("Escribe un importe válido en pesos enteros.");

    } catch (IllegalArgumentException ex) {
        mostrarError(ex.getMessage());
    }
    }//GEN-LAST:event_btnRegistrarPagoActionPerformed

