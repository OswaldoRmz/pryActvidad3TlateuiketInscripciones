private void configurarVentana() {
    setTitle("Inscripciones y mensualidades");

    cmbDisciplina.removeAllItems();
    cmbDisciplina.addItem("Selecciona");
    cmbDisciplina.addItem("Boxeo");
    cmbDisciplina.addItem("MMA");
    cmbDisciplina.addItem("Jiu-jitsu");

    // Valor inicial, mínimo, máximo e incremento.
    spnMensualidad.setModel(
            new SpinnerNumberModel(500, 1, 10000, 1)
    );

    spnImporte.setModel(
            new SpinnerNumberModel(100, 1, 10000, 1)
    );

    // Crea una tabla inicialmente vacía.
    tabla = new DefaultTableModel();
    tabla.addColumn("N.º");
    tabla.addColumn("Importe");

    tblPagos.setModel(tabla);

    // Evita modificar los pagos directamente en las celdas.
    tblPagos.setDefaultEditor(Object.class, null);

    lblTotalPago.setText("$0");
    lblPendiente.setText("$0");
    lblEstado.setText("Sin inscripción");


    btnRegistrarPago.setEnabled(false);
    spnImporte.setEnabled(false);

    pack();
    setLocationRelativeTo(null);
}

private void mostrarResultados() {
    lblTotalPago.setText(
            "$" + inscripcion.calcularTotalPagado()
    );

    lblPendiente.setText(
            "$" + inscripcion.calcularSaldoPendiente()
    );

    if (inscripcion.estaPagada()) {
        lblEstado.setText("Pagada");
        btnRegistrarPago.setEnabled(false);
        spnImporte.setEnabled(false);
    } else {
        lblEstado.setText("Pendiente");
        btnRegistrarPago.setEnabled(true);
        spnImporte.setEnabled(true);
    }

    
    tabla.setRowCount(0);

    // Muestra todos los pagos registrados en el modelo.
    for (int i = 0; i < inscripcion.contarPagos(); i++) {
        tabla.addRow(new Object[]{
            i + 1,
            "$" + inscripcion.obtenerPago(i)
        });
    }
}

private void bloquearDatos() {
    txtNombre1.setEditable(false);
    txtNumero.setEditable(false);
    cmbDisciplina.setEnabled(false);
    spnMensualidad.setEnabled(false);
    btnRegistrarInscripcion.setEnabled(false);
}

private void mostrarError(String mensaje) {
    JOptionPane.showMessageDialog(
            this,
            mensaje,
            "Revisa los datos",
            JOptionPane.WARNING_MESSAGE
    );
}

